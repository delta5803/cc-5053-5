"""Real additive synthesis engine.

Every audible partial is generated by its own sinusoidal oscillator:

    y_n(t) = gain_n * env_n(t) * sin(2*pi*f_n*t + phase_n)

Oscillator phase advances sample by sample and is kept in per-voice state
between processing blocks, so phase and amplitude are interpreted in
continuous time -- a block boundary never restarts an oscillator from its
initial phase.

Partials whose declared frequency cannot be represented at the configured
sample rate are handled by an explicit, declared policy and never fold back
into the output under their original identity:

* ``drop``       -- the partial gain is forced to zero and it is reported;
* ``attenuate``  -- the partial gain is smoothly scaled to zero as its
                    frequency approaches the usable Nyquist limit (a soft
                    band-limit), and the attenuation is reported.

Amplitude changes (partial gains, master gain, note gain) are applied as
linear ramps over a configurable transition time rather than jumps.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Dict, List, Optional

import numpy as np

from .config import TimbreConfig


@dataclass
class BandlimitReport:
    """What the band-limiter did to one declared partial."""

    index: int
    ratio: float
    frequency: float
    usable_nyquist: float
    action: str          # "kept" | "attenuated" | "dropped"
    gain_scale: float    # effective band-limit gain, 0..1
    reason: str = ""


def _ramp_profile(block_size: int, transition_samples: int, position: int) -> np.ndarray:
    """Progress fraction of a transition for each sample in a block.

    0 means the transition just starts, 1 means it has completed. The profile
    is linear in sample time, so applying it as
    ``start + (target - start) * profile`` yields a true linear ramp.
    """
    transition_samples = max(1, transition_samples)
    idx = position + np.arange(block_size, dtype=np.float64) + 1.0
    return np.clip(idx / transition_samples, 0.0, 1.0)


@dataclass
class VoiceSnapshot:
    """Diagnostic view of a live note instance (used by tests and the UI)."""

    note_id: int
    age_seconds: float
    alive: bool
    partial_amplitudes: np.ndarray
    phases: np.ndarray
    instantaneous_contributions: np.ndarray


def _bandlimit_gains(
    frequencies: np.ndarray, nyquist: float, margin: float, mode: str
) -> tuple[np.ndarray, List[BandlimitReport]]:
    usable = nyquist * margin
    scales = np.ones_like(frequencies)
    reports: List[BandlimitReport] = []
    for i, f in enumerate(frequencies):
        if f >= nyquist:
            # Cannot be represented at all. Never fold it back: silence it.
            scales[i] = 0.0
            action, reason = "dropped", "frequency >= Nyquist, cannot be represented"
        elif f >= usable:
            if mode == "drop":
                scales[i] = 0.0
                action, reason = "dropped", f"frequency >= {margin:g} * Nyquist safety margin"
            else:
                # Smooth one-sided cosine taper across [usable, nyquist).
                x = (f - usable) / (nyquist - usable)
                scales[i] = 0.5 * (1.0 + math.cos(math.pi * min(max(x, 0.0), 1.0)))
                action = "attenuated"
                reason = "cosine band-limit taper toward Nyquist"
        else:
            action, reason = "kept", ""
        reports.append(
            BandlimitReport(i, float("nan"), float(f), float(usable), action, float(scales[i]), reason)
        )
    return scales, reports


class NoteVoice:
    """One note instance: a bank of independently running oscillators."""

    def __init__(self, note_id: int, config: TimbreConfig, freq_multiplier: float = 1.0) -> None:
        self.note_id = note_id
        self.sample_rate = float(config.sample_rate)
        self.n = len(config.partials)
        specs = config.partials

        self.ratios = np.array([p.ratio for p in specs], dtype=np.float64)
        self.frequencies = self.ratios * config.base_frequency * freq_multiplier
        self.initial_phases = np.array([p.phase for p in specs], dtype=np.float64)
        self.attacks = np.array([p.attack for p in specs], dtype=np.float64)
        self.decays = np.array([p.decay for p in specs], dtype=np.float64)
        self.releases = np.array([p.release for p in specs], dtype=np.float64)
        self.spec_amplitudes = np.array([p.amplitude for p in specs], dtype=np.float64)

        # Continuous-time oscillator state, carried across every block.
        self.phase = self.initial_phases.copy()
        self.age = 0.0                      # seconds since note-on
        self.released_at: Optional[float] = None
        self.release_env_start = np.zeros(self.n, dtype=np.float64)

        # Per-partial *target* gain (spec amplitude * band-limit scale *
        # solo/mute) and the actual gain being ramped toward it.
        self.bl_scale, self.bandlimit_report = _bandlimit_gains(
            self.frequencies, self.sample_rate / 2.0,
            config.nyquist_margin, config.bandlimit_mode,
        )
        for r, ratio in zip(self.bandlimit_report, self.ratios):
            r.ratio = float(ratio)
        self.target_gain = self.spec_amplitudes * self.bl_scale
        self.gain = self.target_gain.copy()
        self.gain_ramp_start = self.gain.copy()

        self.note_gain = 1.0                # per-note instance level
        self.target_note_gain = 1.0
        self.note_ramp_start = 1.0
        self.transition_samples = max(1, int(round(config.transition_time * self.sample_rate)))
        self.gain_ramp_pos = 0
        self.note_ramp_pos = 0
        self.alive = True
        self._solo_scale = np.ones(self.n, dtype=np.float64)

    # -- parameter changes ----------------------------------------------------

    def _begin_gain_ramp(self) -> None:
        self.gain_ramp_start = self.gain.copy()
        self.gain_ramp_pos = 0

    def set_partial_amplitudes(self, amplitudes: np.ndarray) -> None:
        """Change declared partial amplitudes; existing notes ramp to them."""
        amplitudes = np.asarray(amplitudes, dtype=np.float64)
        if amplitudes.shape != self.spec_amplitudes.shape:
            raise ValueError("partial amplitude vector length changed; build a new config instead")
        self.spec_amplitudes = amplitudes
        new_target = amplitudes * self.bl_scale * self._solo_scale
        if not np.array_equal(new_target, self.target_gain):
            self._begin_gain_ramp()
        self.target_gain = new_target

    def set_solo_mask(self, solo_scale: np.ndarray) -> None:
        solo_scale = np.asarray(solo_scale, dtype=np.float64)
        if not np.array_equal(solo_scale, self._solo_scale):
            self._begin_gain_ramp()
        self._solo_scale = solo_scale
        self.target_gain = self.spec_amplitudes * self.bl_scale * solo_scale

    def set_note_gain(self, value: float) -> None:
        value = max(0.0, float(value))
        if value != self.target_note_gain:
            self.note_ramp_start = self.note_gain
            self.note_ramp_pos = 0
        self.target_note_gain = value

    def note_off(self) -> None:
        if self.released_at is None:
            self.released_at = self.age
            # Freeze the envelope value each partial had at release time.
            self.release_env_start = self._envelope(self.age)

    # -- envelope -------------------------------------------------------------

    def _envelope(self, t: np.ndarray | float) -> np.ndarray | float:
        """Per-partial amplitude envelope at continuous time t (seconds)."""
        t = np.asarray(t, dtype=np.float64)
        scalar = t.ndim == 0
        t = np.atleast_1d(t)
        out = np.zeros((t.size, self.n), dtype=np.float64)

        active = np.ones(t.size, dtype=bool)
        if self.released_at is not None:
            active = t < self.released_at

        # Attack / decay segment (note-on until release).
        ta = t[active]
        seg = np.zeros((ta.size, self.n), dtype=np.float64)
        if ta.size:
            # Per-partial linear attack; an attack time of zero means instant.
            with np.errstate(divide="ignore", invalid="ignore"):
                ramp = ta[:, None] / self.attacks[None, :]
            ramp = np.where(self.attacks[None, :] <= 0.0, 1.0, np.minimum(ramp, 1.0))
            dt = np.maximum(ta[:, None] - self.attacks[None, :], 0.0)
            decay_tau = self.decays[None, :]
            decay_factor = np.where(
                np.isinf(decay_tau), 1.0, np.exp(-dt / np.where(np.isinf(decay_tau), 1.0, decay_tau))
            )
            seg = ramp * decay_factor
        out[active] = seg

        # Release segment (linear per-partial ramp from the frozen value).
        rel = ~active
        if np.any(rel) and self.released_at is not None:
            tr = t[rel] - self.released_at
            with np.errstate(divide="ignore", invalid="ignore"):
                ramp = 1.0 - tr[:, None] / self.releases[None, :]
            instant = self.releases[None, :] <= 0.0
            ramp = np.where(instant, 0.0, np.maximum(ramp, 0.0))
            out[rel] = self.release_env_start[None, :] * ramp
        return out[0] if scalar else out

    # -- rendering ------------------------------------------------------------

    def render_block(self, block_size: int) -> np.ndarray:
        """Render ``block_size`` samples and advance all continuous state."""
        dt = 1.0 / self.sample_rate
        # Sample k of a voice is interpreted at continuous time t = k / sr.
        sample_t = self.age + np.arange(block_size, dtype=np.float64) * dt

        # True linear ramps from the value captured when the target changed.
        p_gain = _ramp_profile(block_size, self.transition_samples, self.gain_ramp_pos)[:, None]
        gain_k = self.gain_ramp_start[None, :] + (self.target_gain[None, :] - self.gain_ramp_start[None, :]) * p_gain
        p_note = _ramp_profile(block_size, self.transition_samples, self.note_ramp_pos)
        note_k = self.note_ramp_start + (self.target_note_gain - self.note_ramp_start) * p_note
        self.gain_ramp_pos += block_size
        self.note_ramp_pos += block_size

        env = self._envelope(sample_t)                       # (B, n)
        # Phase increments per sample; phases accumulate without reset.
        incr = 2.0 * math.pi * self.frequencies * dt
        phases = self.phase + incr * np.arange(block_size, dtype=np.float64)[:, None]
        self.phase = (self.phase + incr * block_size) % (2.0 * math.pi)

        partial_signals = gain_k * env * np.sin(phases)
        block = note_k * partial_signals.sum(axis=1)
        self.gain = gain_k[-1]
        self.note_gain = float(note_k[-1])

        self.age += block_size * dt
        if self.released_at is not None and self.age >= self.released_at + float(np.max(self.releases)):
            # Envelope is mathematically zero beyond this point.
            self.alive = False
        return block

    def snapshot(self) -> VoiceSnapshot:
        t = np.array([self.age])
        env = self._envelope(t)[0]
        contrib = self.note_gain * self.gain * env
        return VoiceSnapshot(
            note_id=self.note_id,
            age_seconds=self.age,
            alive=self.alive,
            partial_amplitudes=(self.gain * env).copy(),
            phases=self.phase.copy(),
            instantaneous_contributions=contrib,
        )


class AdditiveEngine:
    """Polyphonic additive instrument rendering fixed-size blocks."""

    def __init__(self, config: TimbreConfig) -> None:
        self.config = config
        self.voices: Dict[int, NoteVoice] = {}
        self._next_id = 0
        self.master_gain = float(config.master_amplitude)
        self.target_master_gain = self.master_gain
        self.transition_samples = max(1, int(round(config.transition_time * config.sample_rate)))
        self.master_ramp_pos = 0
        self.master_ramp_start = self.master_gain
        # Solo/mute state: scale per partial index, 1 = audible, 0 = muted.
        self.solo_scale = np.ones(len(config.partials), dtype=np.float64)
        self._solo_index: Optional[int] = None
        self.block_counter = 0

    # -- life cycle -----------------------------------------------------------

    def note_on(self, freq_multiplier: float = 1.0, note_gain: float = 1.0) -> int:
        note_id = self._next_id
        self._next_id += 1
        voice = NoteVoice(note_id, self.config, freq_multiplier)
        voice.set_solo_mask(self.solo_scale)
        voice.gain = voice.target_gain.copy()
        voice.set_note_gain(note_gain)
        voice.note_gain = note_gain
        self.voices[note_id] = voice
        return note_id

    def note_off(self, note_id: int) -> None:
        voice = self.voices.get(note_id)
        if voice is not None and voice.released_at is None:
            voice.note_off()

    def all_notes_off(self) -> None:
        for voice in self.voices.values():
            voice.note_off()

    # -- parameter changes (ramped, never abrupt) -----------------------------

    def set_master_gain(self, value: float) -> None:
        value = max(0.0, float(value))
        if value != self.target_master_gain:
            self.master_ramp_start = self.master_gain
            self.master_ramp_pos = 0
        self.target_master_gain = value

    def set_partial_amplitudes(self, amplitudes: List[float] | np.ndarray) -> None:
        amplitudes = np.asarray(amplitudes, dtype=np.float64)
        if amplitudes.size != len(self.config.partials):
            raise ValueError("amplitude count must match partial count")
        for p, a in zip(self.config.partials, amplitudes):
            p.amplitude = float(a)
        for voice in self.voices.values():
            voice.set_partial_amplitudes(amplitudes)

    def set_transition_time(self, seconds: float) -> None:
        self.config.transition_time = max(0.0, float(seconds))
        self.transition_samples = max(1, int(round(self.config.transition_time * self.config.sample_rate)))
        for voice in self.voices.values():
            voice.transition_samples = self.transition_samples

    def set_note_gain(self, note_id: int, value: float) -> None:
        voice = self.voices.get(note_id)
        if voice is not None:
            voice.set_note_gain(value)

    def solo_partial(self, index: Optional[int]) -> None:
        """Solo one partial (None restores the full mix)."""
        n = len(self.config.partials)
        if index is not None and not 0 <= index < n:
            raise IndexError(f"partial index {index} out of range (0..{n - 1})")
        self._solo_index = index
        self.solo_scale = np.zeros(n, dtype=np.float64)
        if index is not None:
            self.solo_scale[index] = 1.0
        else:
            self.solo_scale[:] = 1.0
        for voice in self.voices.values():
            voice.set_solo_mask(self.solo_scale)

    @property
    def solo_index(self) -> Optional[int]:
        return self._solo_index

    # -- rendering ------------------------------------------------------------

    def render_block(self, block_size: int) -> np.ndarray:
        out = np.zeros(block_size, dtype=np.float64)
        profile = _ramp_profile(block_size, self.transition_samples, self.master_ramp_pos)
        master_k = self.master_ramp_start + (self.target_master_gain - self.master_ramp_start) * profile
        self.master_ramp_pos += block_size
        dead: List[int] = []
        for note_id, voice in self.voices.items():
            out += voice.render_block(block_size)
            if not voice.alive:
                dead.append(note_id)
        for note_id in dead:
            del self.voices[note_id]
        self.block_counter += 1
        self.master_gain = float(master_k[-1])
        return out * master_k

    def render_samples(self, sample_count: int, block_size: int = 256) -> np.ndarray:
        """Render an exact number of samples via successive blocks."""
        chunks: List[np.ndarray] = []
        remaining = sample_count
        while remaining > 0:
            size = min(block_size, remaining)
            chunk = self.render_block(size)
            chunks.append(chunk)
            remaining -= size
        return np.concatenate(chunks)

    def bandlimit_report(self, freq_multiplier: float = 1.0) -> List[BandlimitReport]:
        freqs = np.array([p.ratio * self.config.base_frequency * freq_multiplier for p in self.config.partials])
        _, reports = _bandlimit_gains(
            freqs, self.config.nyquist, self.config.nyquist_margin, self.config.bandlimit_mode
        )
        for r, p in zip(reports, self.config.partials):
            r.ratio = p.ratio
        return reports

    def snapshots(self) -> List[VoiceSnapshot]:
        return [v.snapshot() for v in self.voices.values()]
